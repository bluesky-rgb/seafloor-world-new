#!/usr/bin/env python3
"""English translation tooling.
  python3 tools/i18n.py           list untranslated strings (grouped by file) and write i18n/en.js
  python3 tools/i18n.py --check   exit 1 if any string lacks a translation
  python3 tools/i18n.py --keys F  dump untranslated keys of file F (src name or index.html) as JSON
Keys are the Chinese source strings: every $t('...') literal in src/, every text node / title / placeholder /
aria-label / alt in index.html (outside the in-page development log), whitespace collapsed.
i18n/en.json maps key -> English; i18n/en.js is generated from it for the page."""
import html, html.parser, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CJK = re.compile(r'[\u4e00-\u9fff\u3000-\u303f\uff00-\uffef\u201c\u201d]')
norm = lambda s: re.sub(r'\s+', ' ', s).strip()

def js_unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            if n == 'u': out.append(chr(int(s[i + 2:i + 6], 16))); i += 6; continue
            if n == 'x': out.append(chr(int(s[i + 2:i + 4], 16))); i += 4; continue
            out.append({'n': '\n', 't': '\t', 'r': '\r', '0': '\0'}.get(n, n)); i += 2; continue
        out.append(c); i += 1
    return ''.join(out)

def js_keys():
    keys = {}
    for f in sorted(os.listdir(os.path.join(ROOT, 'src'))):
        s = open(os.path.join(ROOT, 'src', f), encoding='utf-8').read()
        for m in re.finditer(r"\$t\(\s*(?:'((?:[^'\\\n]|\\.)*)'|\"((?:[^\"\\\n]|\\.)*)\")\s*\)", s):
            k = js_unescape(m.group(1) if m.group(1) is not None else m.group(2))
            if CJK.search(k): keys.setdefault(k, f)
    return keys

class P(html.parser.HTMLParser):
    def __init__(s):
        super().__init__(convert_charrefs=True); s.stack = []; s.keys = {}; s.skip = 0; s.inlog = 0; s.depth_log = None
    def handle_starttag(s, tag, attrs):
        a = dict(attrs)
        if tag in ('script', 'style'): s.skip += 1
        if tag in ('br', 'img', 'input', 'meta', 'link', 'hr', 'source', 'wbr'):
            pass
        else:
            s.stack.append((tag, a.get('id'), a.get('class')))
        if s.inlog == 0 and tag == 'div' and (a.get('class') or '') == 'log' and any(t[1] == 'logDet' for t in s.stack): s.inlog = len(s.stack)
        for at in ('title', 'placeholder', 'aria-label', 'alt'):
            v = a.get(at)
            if v and CJK.search(v) and not s.inlog: s.keys.setdefault(norm(v), 'index.html')
    def handle_endtag(s, tag):
        if tag in ('script', 'style'): s.skip -= 1
        while s.stack:
            t = s.stack.pop()
            if s.inlog and len(s.stack) < s.inlog: s.inlog = 0
            if t[0] == tag: break
    def handle_data(s, d):
        if s.skip or s.inlog: return
        k = norm(d)
        if k and CJK.search(k): s.keys.setdefault(k, 'index.html')

def html_keys():
    p = P(); p.feed(open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()); return p.keys

def main():
    keys = html_keys(); keys.update({k: v for k, v in js_keys().items() if k not in keys})
    ep = os.path.join(ROOT, 'i18n', 'en.json')
    en = json.load(open(ep, encoding='utf-8')) if os.path.exists(ep) else {}
    missing = {k: f for k, f in keys.items() if k not in en}
    if '--keys' in sys.argv:
        f = sys.argv[sys.argv.index('--keys') + 1]
        print(json.dumps([k for k, g in missing.items() if g == f], ensure_ascii=False, indent=0)); return
    if '--check' in sys.argv:
        if missing: print('i18n: %d strings have no English translation' % len(missing)); sys.exit(1)
        print('i18n: all %d strings translated' % len(keys)); return
    by = {}
    for k, f in missing.items(): by[f] = by.get(f, 0) + 1
    for f in sorted(by): print('%5d  %s' % (by[f], f))
    print('keys %d, translated %d, missing %d' % (len(keys), len(keys) - len(missing), len(missing)))
    used = {k: en[k] for k in keys if k in en}
    open(os.path.join(ROOT, 'i18n', 'en.js'), 'w', encoding='utf-8').write(
        '/* Generated by tools/i18n.py from i18n/en.json — Chinese source text → English. */\nwindow.SEAFLOOR_EN=' + json.dumps(used, ensure_ascii=False, separators=(',', ':')) + ';\n')

if __name__ == '__main__':
    main()
