#!/usr/bin/env python3
"""Concatenate src/*.js (in file-name order) into js/seafloor.js, the script the page loads.

The files in src/ are consecutive pieces of ONE closure: 00-bootstrap.js opens it with
`(function(){` and 99-main-loop.js closes it with `})();`, so every piece shares the same
scope and the order matters (a piece may only use what earlier pieces declared at load time,
or anything inside functions that run later). Edit src/, then run:

    python3 tools/build.py          # writes js/seafloor.js and checks the syntax with node if available
    python3 tools/build.py --check  # fails if js/seafloor.js is out of date (used by CI)
"""
import glob, os, shutil, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = '/* Generated by tools/build.py from src/*.js. Do not edit this file; edit src/ and rebuild. */\n'
parts = sorted(glob.glob(os.path.join(ROOT, 'src', '[0-9][0-9]-*.js')))
code = HEADER + ''.join(open(p, encoding='utf-8').read() for p in parts)
out = os.path.join(ROOT, 'js', 'seafloor.js')
if '--check' in sys.argv:
    cur = open(out, encoding='utf-8').read() if os.path.exists(out) else ''
    if cur != code:
        sys.exit('js/seafloor.js is out of date: run python3 tools/build.py and commit the result.')
    print('js/seafloor.js is up to date (%d parts)' % len(parts))
else:
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8').write(code)
    print('wrote js/seafloor.js from %d parts, %d lines' % (len(parts), code.count('\n')))
if shutil.which('node'):
    r = subprocess.run(['node', '--check', out], capture_output=True, text=True)
    if r.returncode:
        sys.exit('syntax error:\n' + r.stderr)
    print('node --check: OK')
